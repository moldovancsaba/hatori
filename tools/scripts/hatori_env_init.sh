ENV
  chmod 600 "$target"
  echo "Created $target"
else
  chmod 600 "$target"
  echo "Exists $target"
fi

echo "Next steps:"
echo "- Edit $target and set HATORI_MLX_MODEL + writer route model for Apertus."
echo "- Run bootstrap: make bootstrap"
echo "- Token value is stored in $target (not printed)."
